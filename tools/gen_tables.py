"""Precompute GrooveDeck's lookup tables (the chip has no FPU): firmware/src/tables.h.
   python3 tools/gen_tables.py"""
import math
from pathlib import Path

FS = 44100.0
INC1HZ = 2 ** 32 / FS            # phase step per sample for 1 Hz


def tbl(name, vals, ctype="uint32_t"):
    rows = []
    for i in range(0, len(vals), 8):
        rows.append("    " + ", ".join(f"{v}u" for v in vals[i:i + 8]) + ",")
    return f"static const {ctype} {name}[{len(vals)}] = {{\n" + "\n".join(rows) + "\n};\n"


# decay 0..127 -> time constant 6 ms .. 1.5 s (exponential); per-sample multiplier in Q16
decc = []
for p in range(128):
    tau = 0.006 * 250.0 ** (p / 127.0)
    decc.append(min(65535, round(math.exp(-1.0 / (tau * FS)) * 65536)))

# tune 0..127 -> frequency ratio 0.5 .. 2.0 (centre 64 = 1.0), Q12
tunem = [round(2.0 ** ((p - 64) / 64.0) * 4096) for p in range(128)]

# the 808 hat: six square oscillators; the cowbell: two; the rim: a low and a high sine
hat = [round(f * INC1HZ) for f in (205.3, 304.4, 369.6, 522.7, 540.0, 800.0)]
cow = [round(f * INC1HZ) for f in (540.0, 800.0)]
rim = [round(f * INC1HZ) for f in (450.0, 1660.0)]

out = ["/* SPDX-License-Identifier: GPL-3.0-only */",
       "/* generated by tools/gen_tables.py: do not edit */",
       tbl("DECC", decc), tbl("TUNEM", tunem), tbl("HATINC", hat), tbl("COWINC", cow), tbl("RIMINC", rim)]
dst = Path(__file__).resolve().parent.parent / "firmware" / "src" / "tables.h"
dst.write_text("\n".join(out), newline="\n")
print("wrote", dst, f"(DECC {decc[0]}..{decc[-1]}, TUNEM {tunem[0]}..{tunem[-1]})")
